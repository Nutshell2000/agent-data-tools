// Builds src/data/axe-source.generated.ts: the minified axe-core engine as a string, which /audit/website evaluates inside
// the hosted browser page to run WCAG checks. Bundled rather than loaded from a CDN, so a page's Content-Security-Policy
// or a CDN outage cannot stop the audit, and the version is pinned by package.json (devDependency, exact).
// Licence: axe-core is MPL-2.0; the file is shipped unmodified with its own licence header, which this keeps.
//   node scripts/build-axe-source.mjs        (rerun after upgrading axe-core)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const pkg = require("axe-core/package.json");
const source = readFileSync(require.resolve("axe-core/axe.min.js"), "utf8");
if (!source.includes("axe.run") && !source.includes("run:")) throw new Error("axe.min.js does not look like axe-core");
const out = `// Generated by scripts/build-axe-source.mjs from axe-core ${pkg.version} (MPL-2.0, unmodified). Do not edit.
export const AXE_VERSION = ${JSON.stringify(pkg.version)};
export const AXE_SOURCE = ${JSON.stringify(source)};
`;
writeFileSync(new URL("../src/data/axe-source.generated.ts", import.meta.url), out);
console.log(`axe-core ${pkg.version}: ${source.length} characters`);
