// Builds src/data/airports.generated.ts from OurAirports (ourairports.com/data, public domain): every large and medium
// airport and every small one with an IATA code, with codes, name, city, country, coordinates, elevation and links.
// Rerun monthly: node scripts/fetch-airports.mjs
import { writeFileSync } from "node:fs";

const URL_CSV = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const res = await fetch(URL_CSV);
if (!res.ok) throw new Error(`OurAirports answered HTTP ${res.status}`);
const text = await res.text();

/** RFC 4180 CSV rows (quoted fields, doubled quotes). */
function rows(csv) {
  const out = []; let row = [], field = "", q = false;
  for (let i = 0; i < csv.length; i++) {
    const ch = csv[i];
    if (q) { if (ch === '"') { if (csv[i + 1] === '"') { field += '"'; i++; } else q = false; } else field += ch; }
    else if (ch === '"') q = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n") { row.push(field); out.push(row); row = []; field = ""; }
    else if (ch !== "\r") field += ch;
  }
  if (field || row.length) { row.push(field); out.push(row); }
  return out;
}
const [head, ...body] = rows(text);
const col = Object.fromEntries(head.map((h, i) => [h, i]));
const keep = body.filter((r) => r.length === head.length && (r[col.type] === "large_airport" || r[col.type] === "medium_airport" || (r[col.type] === "small_airport" && r[col.iata_code])) && r[col.scheduled_service] !== undefined);
// Compact tuples: [ident(ICAO or local), iata, name, municipality, iso_country, iso_region, lat, lon, elevation_ft, type, scheduled, wiki, home]
const T = { large_airport: "L", medium_airport: "M", small_airport: "S" };
const data = keep.map((r) => [
  r[col.ident], r[col.iata_code] || "", r[col.name], r[col.municipality] || "", r[col.iso_country], r[col.iso_region],
  Math.round(Number(r[col.latitude_deg]) * 1e4) / 1e4, Math.round(Number(r[col.longitude_deg]) * 1e4) / 1e4,
  r[col.elevation_ft] ? Number(r[col.elevation_ft]) : null, T[r[col.type]], r[col.scheduled_service] === "yes" ? 1 : 0,
  r[col.wikipedia_link] || "", r[col.home_link] || "",
]);
const date = new Date().toISOString().slice(0, 10);
writeFileSync(new URL("../src/data/airports.generated.ts", import.meta.url),
  `// Generated by scripts/fetch-airports.mjs from OurAirports (public domain) on ${date}. Do not edit by hand.\n` +
  `// [ident, iata, name, city, country, region, lat, lon, elevationFt, type L|M|S, scheduledService 0|1, wikipedia, homepage]\n` +
  `export const AIRPORTS_DATE = "${date}";\nexport const AIRPORTS: [string, string, string, string, string, string, number, number, number | null, string, number, string, string][] = ${JSON.stringify(data)};\n`);
console.log(`airports: ${data.length} kept of ${body.length}`);
