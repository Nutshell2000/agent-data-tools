import { build } from "esbuild";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

// Compile exact public schemas once at build time. These validators require no runtime schema compilation or eval.
export async function generateOutputValidators() {
  const built = await build({entryPoints:["src/endpoints.ts"],bundle:true,platform:"node",format:"esm",write:false});
  const { ENDPOINTS } = await import("data:text/javascript;base64," + Buffer.from(built.outputFiles[0].text).toString("base64"));
  const ajv = new Ajv2020({strict:false, code:{source:true,esm:true}, validateFormats:false});
  const names = {};
  for (const endpoint of ENDPOINTS.filter(e => e.outputSchema)) {
    const name = "validate_" + endpoint.path.slice(1).replaceAll("-", "_");
    ajv.addSchema(endpoint.outputSchema, endpoint.path);
    names[name] = endpoint.path;
  }
  return "// @ts-nocheck\n// Generated by scripts/build-output-validators.mjs; do not edit.\n" + standaloneCode(ajv, names) + "\n";
}
async function main() {
  const args = process.argv.slice(2);
  if(args.length > 1 || (args.length && args[0] !== "--check")) throw Error("Usage: node scripts/build-output-validators.mjs [--check]");
  const path = "src/lib/output-validators.generated.ts", source = await generateOutputValidators();
  if(args[0] === "--check") {
    if((await readFile(path,"utf8")).replaceAll("\r\n","\n") !== source) throw Error("Output validators are stale; run npm run build:contracts");
    console.log("Exact output validators match public schemas.");
  } else {await writeFile(path,source);console.log("Generated exact output validators.");}
}
if(process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch(e=>{console.error(e.message);process.exitCode=1;});
