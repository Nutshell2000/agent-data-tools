// Builds src/data/world-bank.generated.ts: a snapshot of a few World Bank indicators for every country, the last
// YEARS years. The tools in src/routes/econ.ts read this file instead of the live API, because the live API answered
// 7-20 s for a cold country/indicator pair on 22 Oct 2026 (a paid call has an 8 s budget) and the data changes yearly.
// Licence: World Bank Open Data, CC BY 4.0 (datacatalog.worldbank.org/public-licenses#cc-by); every answer names it.
//   node scripts/fetch-world-bank.mjs        (about 10 requests; rerun monthly or when a tool adds an indicator)
import { writeFileSync } from "node:fs";

const YEARS = 10;
/** Indicator code -> short key used in the tools. Keep in step with src/routes/econ.ts. */
export const INDICATORS = {
  "NY.GDP.MKTP.CD": "gdpUsd",
  "NY.GDP.MKTP.KD.ZG": "gdpGrowthPct",
  "NY.GDP.PCAP.CD": "gdpPerCapitaUsd",
  "FP.CPI.TOTL.ZG": "inflationPct",
  "SP.POP.TOTL": "population",
  "SP.POP.GROW": "populationGrowthPct",
  "SP.URB.TOTL.IN.ZS": "urbanPct",
  "SL.UEM.TOTL.ZS": "unemploymentPct",
  "SL.UEM.1524.ZS": "youthUnemploymentPct",
};

const get = async (url) => {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(60_000), headers: { "user-agent": "AgentDataTools/1.0 (spellz111122@gmail.com)" } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      return await res.json();
    } catch (e) {
      if (attempt >= 3) throw e;
      console.error(`retry ${attempt}: ${url} (${e.message})`);
    }
  }
};

const [, countryRows] = await get("https://api.worldbank.org/v2/country?format=json&per_page=400");
const countries = {};
for (const c of countryRows) {
  if (c.region?.value === "Aggregates") continue;
  countries[c.id] = { name: c.name, iso2: c.iso2Code, region: c.region.value, income: c.incomeLevel?.value ?? null, capital: c.capitalCity || null };
}
const names = {};
for (const [, meta] of Object.entries(INDICATORS)) names[meta] = null;
const series = {};
for (const [code, key] of Object.entries(INDICATORS)) {
  const [page, rows] = await get(`https://api.worldbank.org/v2/country/all/indicator/${code}?format=json&mrv=${YEARS}&per_page=20000`);
  if (page.pages !== 1) throw new Error(`${code}: ${page.pages} pages`);
  names[key] = rows[0]?.indicator?.value ?? code;
  const byCountry = {};
  for (const r of rows ?? []) {
    if (r.value === null || !countries[r.countryiso3code]) continue;
    (byCountry[r.countryiso3code] ??= {})[r.date] = Number(r.value);
  }
  series[key] = byCountry;
  console.error(`${code} ${key}: ${Object.keys(byCountry).length} countries`);
}
const fetchedAt = new Date().toISOString().slice(0, 10);
const out = `// Generated by scripts/fetch-world-bank.mjs on ${fetchedAt}. Do not edit; rerun the script.
// Source: World Bank Open Data (api.worldbank.org/v2), CC BY 4.0. ${Object.keys(countries).length} countries, last ${YEARS} years.
export const WORLD_BANK_FETCHED = "${fetchedAt}";
export const WORLD_BANK_COUNTRIES: Record<string, { name: string; iso2: string; region: string; income: string | null; capital: string | null }> = ${JSON.stringify(countries)};
export const WORLD_BANK_INDICATOR_NAMES: Record<string, string> = ${JSON.stringify(names)};
export const WORLD_BANK_SERIES: Record<string, Record<string, Record<string, number>>> = ${JSON.stringify(series)};
`;
writeFileSync(new URL("../src/data/world-bank.generated.ts", import.meta.url), out);
console.error(`wrote src/data/world-bank.generated.ts (${(out.length / 1024).toFixed(0)} KB)`);
