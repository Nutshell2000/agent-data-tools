"""Builds the 1200x630 preview card served at /og.png (src/lib/og-image.ts).

x402scan shows an origin's og:image beside its listing and reuses it as the share image.
Needs Pillow and the DejaVu fonts; run: python3 scripts/build-og-image.py
"""
import base64
import io

from PIL import Image, ImageDraw, ImageFont

BG, FG, MUTED, ACCENT, LINE = "#fbfaf7", "#1d1b16", "#6b665c", "#0b6e4f", "#e3ded3"
FONTS = "/usr/share/fonts/truetype/dejavu/"
bold = lambda size: ImageFont.truetype(FONTS + "DejaVuSans-Bold.ttf", size)
regular = lambda size: ImageFont.truetype(FONTS + "DejaVuSans.ttf", size)

img = Image.new("RGB", (1200, 630), BG)
d = ImageDraw.Draw(img)
d.rectangle([0, 0, 1200, 14], fill=ACCENT)
d.text((80, 90), "Agent Data Tools", font=bold(84), fill=FG)
d.text((80, 200), "Pay-per-call data tools for AI agents over x402", font=regular(38), fill=MUTED)
rows = [
    "Token prices, wallet and chain data on Base",
    "OFAC sanctions screening and company records",
    "Web pages, PDFs, feeds and link previews",
]
for i, row in enumerate(rows):
    y = 300 + i * 70
    d.ellipse([84, y + 14, 104, y + 34], fill=ACCENT)
    d.text((126, y), row, font=regular(36), fill=FG)
d.line([80, 525, 1120, 525], fill=LINE, width=2)
d.text((80, 550), "From $0.001 per call, USDC on Base. No account or API key.", font=bold(30), fill=ACCENT)

buf = io.BytesIO()
img.quantize(colors=32).save(buf, "PNG", optimize=True)
data = base64.b64encode(buf.getvalue()).decode()
with open("src/lib/og-image.ts", "w") as f:
    f.write("// Generated by scripts/build-og-image.py. 1200x630 preview card for /og.png (og:image).\n")
    f.write(f'export const OG_IMAGE_PNG_BASE64 =\n  "{data}";\n')
print(len(buf.getvalue()), "bytes")
