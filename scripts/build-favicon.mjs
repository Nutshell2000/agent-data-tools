// Generates src/lib/favicon.ts: a 32x32 icon (green square, white braces) as a BMP-based .ico,
// embedded as base64 so the Worker serves /favicon.ico without a static asset.
//   node scripts/build-favicon.mjs
import { writeFileSync } from "node:fs";

const N = 32;
const px = Array.from({ length: N }, () => Array(N).fill([0x1f, 0x7a, 0x4d, 255])); // RGBA green
const white = [255, 255, 255, 255], clear = [0, 0, 0, 0];
// Rounded corners.
for (const [y, x] of [[0, 0], [0, 1], [1, 0], [0, 31], [0, 30], [1, 31], [31, 0], [31, 1], [30, 0], [31, 31], [31, 30], [30, 31]]) px[y][x] = clear;
// Braces "{ }" drawn with 2-pixel strokes.
const set = (x, y) => { for (const dx of [0, 1]) px[y][x + dx] = white; };
function brace(x0, dir) {
  for (let y = 8; y <= 23; y++) {
    const mid = y >= 15 && y <= 16;
    const x = mid ? x0 - 3 * dir : (y === 8 || y === 23) ? x0 + 2 * dir : x0;
    set(x, y);
    if (y === 8 || y === 23) set(x0, y);
  }
}
brace(10, 1);
brace(20, -1);

// BMP DIB (bottom-up BGRA) + AND mask, inside an ICO container.
const dib = Buffer.alloc(40 + N * N * 4 + N * 4);
dib.writeUInt32LE(40, 0); dib.writeInt32LE(N, 4); dib.writeInt32LE(N * 2, 8); dib.writeUInt16LE(1, 12); dib.writeUInt16LE(32, 14);
dib.writeUInt32LE(N * N * 4 + N * 4, 20);
let o = 40;
for (let y = N - 1; y >= 0; y--) for (let x = 0; x < N; x++) { const [r, g, b, a] = px[y][x]; dib[o++] = b; dib[o++] = g; dib[o++] = r; dib[o++] = a; }
// AND mask stays zero: alpha channel carries transparency.
const header = Buffer.alloc(6 + 16);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
header[6] = N; header[7] = N; header[8] = 0; header[9] = 0; header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
header.writeUInt32LE(dib.length, 14); header.writeUInt32LE(22, 18);
const ico = Buffer.concat([header, dib]);
writeFileSync(new URL("../src/lib/favicon.ts", import.meta.url),
  `// Generated by scripts/build-favicon.mjs. 32x32 icon for /favicon.ico (directories show it next to the API).\nexport const FAVICON_ICO_BASE64 =\n  "${ico.toString("base64")}";\n`);
console.log(`favicon ${ico.length} bytes`);
