"""Builds src/data/invoice-font.generated.ts: the two fonts the ZUGFeRD PDF writer embeds.

A PDF/A file must embed every font it uses, and a Worker has no fonts. Noto Sans Regular and Bold (SIL Open Font
License 1.1, no reserved font name) are cut down to the characters European invoices use, and their bytes, metrics,
character map and glyph widths are written as one TypeScript module, so the Worker parses no font at run time.

Usage (needs `pip install fonttools`):
    python scripts/build-invoice-font.py <folder with NotoSans-Regular.ttf and NotoSans-Bold.ttf>
Source: https://github.com/notofonts/notofonts.github.io (fonts/NotoSans/hinted/ttf).
"""

import base64
import io
import sys
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

UNICODES = "U+0020-007E,U+00A0-017F,U+2010-2015,U+2018-201E,U+2022,U+2026,U+2030,U+20AC"
OUT = Path(__file__).resolve().parent.parent / "src" / "data" / "invoice-font.generated.ts"


def build(path: Path) -> dict:
    options = subset.Options()
    options.hinting = False
    options.layout_features = []
    options.name_IDs = [1, 2, 3, 4, 6]
    options.notdef_outline = True
    font = TTFont(str(path))
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=subset.parse_unicodes(UNICODES))
    subsetter.subset(font)
    data = io.BytesIO()
    font.save(data)
    font = TTFont(io.BytesIO(data.getvalue()))
    units = font["head"].unitsPerEm
    scale = 1000 / units
    order = font.getGlyphOrder()
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    os2 = font["OS/2"]
    return {
        "bytes": data.getvalue(),
        "ascent": round(font["hhea"].ascent * scale),
        "descent": round(font["hhea"].descent * scale),
        "capHeight": round(getattr(os2, "sCapHeight", 714) * scale),
        "bbox": [round(v * scale) for v in (font["head"].xMin, font["head"].yMin, font["head"].xMax, font["head"].yMax)],
        "cmap": sorted((cp, order.index(name)) for cp, name in cmap.items()),
        "widths": [round(hmtx[name][0] * scale) for name in order],
    }


def ts(name: str, postscript: str, stem: int, f: dict) -> str:
    cmap = ",".join(f"[{cp},{gid}]" for cp, gid in f["cmap"])
    widths = ",".join(str(w) for w in f["widths"])
    return (
        f"export const {name}: InvoiceFont = {{\n"
        f'  name: "{postscript}", stemV: {stem}, ascent: {f["ascent"]}, descent: {f["descent"]}, capHeight: {f["capHeight"]}, bbox: {f["bbox"]},\n'
        f"  cmap: new Map([{cmap}]),\n"
        f"  widths: [{widths}],\n"
        f'  base64: "{base64.b64encode(f["bytes"]).decode()}",\n'
        f"}};\n"
    )


def main() -> int:
    folder = Path(sys.argv[1])
    regular, bold = build(folder / "NotoSans-Regular.ttf"), build(folder / "NotoSans-Bold.ttf")
    OUT.write_text(
        "// GENERATED by scripts/build-invoice-font.py: do not edit. Noto Sans Regular and Bold, cut down to the characters\n"
        "// European invoices use. Copyright 2022 The Noto Project Authors (https://github.com/notofonts/latin-greek-cyrillic),\n"
        "// licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).\n"
        "export interface InvoiceFont {\n"
        "  /** PostScript name, with the subset tag PDF asks for. */\n"
        "  name: string;\n"
        "  stemV: number; ascent: number; descent: number; capHeight: number; bbox: number[];\n"
        "  /** Unicode code point to glyph id. */\n"
        "  cmap: Map<number, number>;\n"
        "  /** Advance width per glyph id, in 1/1000 of the font size. */\n"
        "  widths: number[];\n"
        "  /** The TrueType file. */\n"
        "  base64: string;\n"
        "}\n\n"
        + ts("FONT_REGULAR", "ADTINV+NotoSans-Regular", 88, regular)
        + "\n"
        + ts("FONT_BOLD", "ADTINB+NotoSans-Bold", 140, bold),
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT} {OUT.stat().st_size} bytes; glyphs {len(regular['widths'])} + {len(bold['widths'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
